def build_summary():
    wb = Workbook()
    ws = wb.active
    ws.title = "汇总说明"
    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["B"].width = 60
    ws.column_dimensions["C"].width = 34
    ws.column_dimensions["D"].width = 34
    for r, row in enumerate(summary_rows, 1):
        for c, v in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=v if v != "" else None)
            cell.font = body_font
            cell.alignment = left if c == 2 else Alignment(horizontal="left", vertical="center", wrap_text=True)
    # 标题
    ws.cell(row=1, column=1).font = Font(name="微软雅黑", size=18, bold=True, color=BRAND)
    ws.cell(row=1, column=2).font = Font(name="微软雅黑", size=18, bold=True, color="1F2937")
    # 端别表头
    for c in range(1, 4):
        cell = ws.cell(row=8, column=c)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = center
    # 统计表头
    for c in range(1, 4):
        cell = ws.cell(row=13, column=c)
        cell.fill = PatternFill("solid", fgColor=ORANGE)
        cell.font = header_font
        cell.alignment = center
    ws.row_dimensions[1].height = 30
    ws.row_dimensions[2].height = 12
    ws.row_dimensions[6].height = 12
    ws.row_dimensions[12].height = 12
    return wb


def build():
    wb = build_summary()
    sheets = [
        ("宠物主端功能清单", [("序号", 6), ("一级模块", 16), ("页面/子模块", 22), ("功能点", 26), ("功能说明与操作", 70), ("状态", 10), ("备注", 18)]),
        ("医生端功能清单", [("序号", 6), ("一级模块", 14), ("页面/子模块", 22), ("功能点", 24), ("功能说明与操作", 70), ("状态", 10), ("备注", 18)]),
        ("运营端功能清单", [("序号", 6), ("一级模块", 16), ("页面/子模块", 22), ("功能点", 24), ("功能说明与操作", 70), ("状态", 10), ("备注", 18)]),
    ]
    for title, headers in sheets:
        ws = wb.create_sheet(title=title)
        # 写入表头（序号列）
        for c, (h, w) in enumerate(headers, 1):
            cell = ws.cell(row=1, column=c, value=h)
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = center
            cell.border = border
            ws.column_dimensions[get_column_letter(c)].width = w
        ws.freeze_panes = "A2"
        ws.row_dimensions[1].height = 24
        row = 2
        seq = 1
        prev_mod = None
        start = 2
        for item in data_entries[title]:
            mod, name, feature, desc, status, note = item
            values = [seq, mod, name, feature, desc, status, note]
            for c, v in enumerate(values, 1):
                cell = ws.cell(row=row, column=c, value=v)
                cell.border = border
                if c in (1, 6, 7):
                    cell.alignment = center
                else:
                    cell.alignment = left
                if c == 2:
                    cell.fill = mod_fill
                    cell.font = mod_font
                elif c == 6:
                    cell.font = body_font
                else:
                    cell.font = body_font
                if status == "占位" and c == 6:
                    cell.fill = placeholder_fill
                    cell.font = placeholder_font
            desc_len = len(str(desc))
            est = max(2, min(14, (desc_len // 50) + 1))
            ws.row_dimensions[row].height = 18 * est
            if mod != prev_mod and prev_mod is not None:
                # 模块间合并单元格（一级模块列）
                if row - 1 > start:
                    ws.merge_cells(start_row=start, start_column=2, end_row=row - 1, end_column=2)
                start = row
            prev_mod = mod
            row += 1
            seq += 1
        if row - 1 > start:
            ws.merge_cells(start_row=start, start_column=2, end_row=row - 1, end_column=2)
    wb.save(OUT)
    print("saved:", OUT)


if __name__ == "__main__":
    build()
